function schemaRows(node, p, rows, required = new Set()) {
  const alts = node.anyOf && !isTime(node) ? node.anyOf : [node];
  for (const a of alts) {
    if (a.type === 'object' && a.properties) {
      const req = new Set(a.required ?? []);
      for (const [k, v] of Object.entries(a.properties)) {
        if (k === '$schema') continue;
        const key = p ? `${p}.${k}` : k;
        if (!rows.has(key)) rows.set(key, { schema: v, required: req.has(k) && v.default === undefined });
        schemaRows(v, key, rows);
      }
    } else if (a.type === 'array' && a.items) schemaRows(a.items, `${p}[]`, rows, required);
  }
  return rows;
}

