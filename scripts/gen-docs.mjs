// ---------------------------------------------------------------- JSON Schema helpers

const isTime = (s) =>
  Array.isArray(s?.anyOf) &&
  s.anyOf.length === 2 &&
  s.anyOf.some((a) => a.type === 'string') &&
  s.anyOf.some((a) => a.type === 'number');

function typeOf(s) {
  if (!s) return 'any';
  if (isTime(s)) return 'time';
  if (s.enum && s.enum.length > 40) return 'icon name ([list](#icons))';
  if (s.enum) return s.enum.map((v) => code(v)).join(' \\| ');
  if (s.const !== undefined) return code(s.const);
  if (s.anyOf) return [...new Set(s.anyOf.map(typeOf))].join(' \\| ');
  if (s.type === 'array') return `${s.items?.anyOf ? `(${typeOf(s.items)})` : typeOf(s.items)}[]`;
  if (s.type === 'object') return s.properties ? 'object' : 'map';
  return Array.isArray(s.type) ? s.type.join(' \\| ') : (s.type ?? 'any');
}

function limits(s) {
  const out = [];
  const one = (x) => {
    if (x.minimum !== undefined) out.push(`≥ ${x.minimum}`);
    if (x.exclusiveMinimum !== undefined) out.push(`> ${x.exclusiveMinimum}`);
    if (x.maximum !== undefined) out.push(`≤ ${x.maximum}`);
    if (x.minLength !== undefined && x.minLength > 1) out.push(`min ${x.minLength} chars`);
    if (x.maxLength !== undefined) out.push(`max ${x.maxLength} chars`);
    if (x.minItems !== undefined) out.push(`min ${x.minItems} items`);
    if (x.maxItems !== undefined) out.push(`max ${x.maxItems} items`);
    if (x.pattern) out.push(`pattern ${code(x.pattern)}`);
  };
  if (!isTime(s)) one(s);
  return out.join(', ');
}

const fmtDefault = (v) => (v === undefined ? '' : code(JSON.stringify(v)));

