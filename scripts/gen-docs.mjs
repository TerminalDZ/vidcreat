function inputRows(schema, L) {
  const props = schema.properties ?? {};
  const req = new Set(schema.required ?? []);
  const keys = Object.keys(props);
  if (!keys.length) return `${L('No arguments.', 'بلا وسائط.')}\n`;
  let md = `| ${L('Argument', 'الوسيط')} | ${L('Type', 'النوع')} | ${L('Required', 'إلزامي')} | ${L('Default', 'الافتراضي')} | ${L('Description', 'الوصف')} |\n|---|---|---|---|---|\n`;
  for (const k of keys) {
    const v = props[k];
    md += `| ${code(k)} | ${typeOf(v)} | ${req.has(k) ? L('yes', 'نعم') : ''} | ${fmtDefault(v.default)} | ${esc(v.description ?? '')} |\n`;
  }
  return md;
}

