/** Gallery scene that shows each component (first scene that uses it). */
function galleryScenes() {
  const file = path.join(ROOT, 'fixtures/golden/components/episode.yaml');
  const spec = parseYaml(readFileSync(file, 'utf8'));
  const map = new Map();
  for (const scene of spec.scenes ?? [])
    for (const el of scene.elements ?? []) if (!map.has(el.use)) map.set(el.use, scene.id);
  return map;
}

/** A 1/3-scale copy of a golden frame (box filter), so the site stays light. */
function thumbnail(file) {
  const src = PNG.sync.read(readFileSync(file));
  const f = 3;
  const w = Math.floor(src.width / f);
  const h = Math.floor(src.height / f);
  const out = new PNG({ width: w, height: h });
  for (let y = 0; y < h; y++)
    for (let x = 0; x < w; x++) {
      const acc = [0, 0, 0, 0];
      for (let dy = 0; dy < f; dy++)
        for (let dx = 0; dx < f; dx++) {
          const i = ((y * f + dy) * src.width + (x * f + dx)) * 4;
          for (let c = 0; c < 4; c++) acc[c] += src.data[i + c];
        }
      const o = (y * w + x) * 4;
      for (let c = 0; c < 4; c++) out.data[o + c] = Math.round(acc[c] / (f * f));
    }
  return PNG.sync.write(out, { colorType: 6, deflateLevel: 9, filterType: 4 });
}

function componentFrames() {
  const files = new Map();
  const dir = path.join(ROOT, 'fixtures/golden/components/frames');
  const scenes = galleryScenes();
  const frames = new Map();
  for (const [component, scene] of scenes) {
    const f = path.join(dir, `${scene}.png`);
    if (!existsSync(f)) continue;
    frames.set(component, scene);
    const out = `docs/public/components/${scene}.png`;
    if (!files.has(out)) files.set(out, thumbnail(f));
  }
  return { files, frames };
}

