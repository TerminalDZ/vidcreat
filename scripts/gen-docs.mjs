// ---------------------------------------------------------------- all

async function format(file, text) {
  const options = (await prettier.resolveConfig(path.join(ROOT, file))) ?? {};
  return prettier.format(text, { ...options, filepath: path.join(ROOT, file) });
}

/** Every generated file: relative path → content (string or Buffer). */
export async function generateDocs() {
  const out = new Map();
  const { files: images, frames } = componentFrames();
  const clients = await loadClients();
  for (const lang of ['en', 'ar']) {
    const pages = {
      'episode-format.md': episodeFormat(lang),
      'components.md': componentsPage(lang, frames),
      'cli.md': cliPage(lang),
      'mcp-tools.md': toolsPage(lang),
      'ai-clients.md': clientsPage(lang, clients),
      'packs.md': packsPage(lang),
    };
    for (const [name, text] of Object.entries(pages)) {
      const file = `${prefix(lang)}/${name}`;
      out.set(file, await format(file, text));
    }
  }
  for (const [f, buf] of [...images].sort(([a], [b]) => a.localeCompare(b))) out.set(f, buf);
  const components = await componentsDoc();
  out.set('docs/components.md', components);
  out.set(
    'llms-full.txt',
    llmsFull((f) => (out.has(f) ? String(out.get(f)) : readFileSync(path.join(ROOT, f), 'utf8'))),
  );
  return out;
}

/** Generated files that exist on disk but are no longer produced (removed components). */
export function staleFiles(out) {
  const dir = path.join(ROOT, 'docs/public/components');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .map((f) => `docs/public/components/${f}`)
    .filter((f) => !out.has(f));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = await generateDocs();
  for (const [file, content] of out) {
    const abs = path.join(ROOT, file);
    // Same pixels: keep the committed PNG (another zlib may compress it differently).
    if (file.endsWith('.png') && existsSync(abs)) {
      const [a, b] = [PNG.sync.read(readFileSync(abs)), PNG.sync.read(content)];
      if (a.width === b.width && a.height === b.height && Buffer.compare(a.data, b.data) === 0) continue;
    }
    mkdirSync(path.dirname(abs), { recursive: true });
    writeFileSync(abs, content);
  }
  const stale = staleFiles(out);
  if (stale.length) console.warn(`no longer generated (delete them): ${stale.join(', ')}`);
  console.log(`gen-docs: ${out.size} files`);
}
