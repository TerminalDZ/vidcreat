// Builds llms-full.txt: every guide a model needs in one file (AGENTS.md, the authoring guide, the
// component reference, the English user guide and the skills), served by the dashboard at /llms-full.txt.
//   node scripts/gen-llms.mjs      (pnpm docs:llms)
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (...p) =>
  path
    .join(...p)
    .split(path.sep)
    .join('/');

/** Markdown files under a folder, recursively, in a stable order. */
const walk = (dir) =>
  existsSync(path.join(root, dir))
    ? readdirSync(path.join(root, dir))
        .sort()
        .flatMap((f) =>
          statSync(path.join(root, dir, f)).isDirectory()
            ? walk(rel(dir, f))
            : f.endsWith('.md')
              ? [rel(dir, f)]
              : [],
        )
    : [];

/** The source files of llms-full.txt, in order. */
export function llmsFiles() {
  return [
    'AGENTS.md',
    'docs/authoring.md',
    'docs/components.md',
    ...walk('docs/guide').filter((f) => !f.endsWith('/changelog.md')),
    ...readdirSync(path.join(root, 'skills'))
      .sort()
      .filter((d) => existsSync(path.join(root, 'skills', d, 'SKILL.md')))
      .map((d) => rel('skills', d, 'SKILL.md')),
  ].filter((f) => existsSync(path.join(root, f)));
}

/**
 * The text of llms-full.txt. `read(file)` may return generated content that is not written yet.
 */
export function llmsFull(read = (f) => readFileSync(path.join(root, f), 'utf8')) {
  const files = llmsFiles();
  const parts = files.map((f) => {
    const text = read(f)
      .replace(/^\uFEFF/, '')
      .replace(/\r\n/g, '\n')
      .replace(/^---\n[\s\S]*?\n---\n+/, '')
      .trimEnd();
    return `<!-- file: ${f} -->\n\n${text}\n`;
  });
  const head = `# ReelForge: full documentation for language models

> Generated by scripts/gen-llms.mjs from ${files.length} files. The short index is llms.txt.
`;
  return `${head}\n${parts.join('\n---\n\n')}`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(path.join(root, 'llms-full.txt'), llmsFull());
  console.log(`llms-full.txt: ${llmsFiles().length} files`);
}
