// One-off generator for the `map` component's outline data (packages/runtime/src/data/world.ts).
// Source: Natural Earth 1:110m Admin 0 – Countries (public domain, https://www.naturalearthdata.com).
// Rings are simplified (Douglas–Peucker), tiny islands dropped, and coordinates stored as integer
// tenths of a degree, so the module stays small (< 150 KB). Antarctica is left out.
// Usage: node scripts/gen-world-map.mjs [path-or-url-to ne_110m_admin_0_countries.geojson]
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const SOURCE =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_admin_0_countries.geojson';
const TOLERANCE = 0.18; // degrees
const MIN_AREA = 0.6; // square degrees; smaller islands are dropped (the largest ring always stays)

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2] ?? SOURCE;
const geo = /^https?:/.test(src)
  ? await (await fetch(src)).json()
  : JSON.parse(readFileSync(path.resolve(src), 'utf8'));

function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a];
    const [bx, by] = pts[b];
    const len = Math.hypot(bx - ax, by - ay) || 1e-9;
    let best = -1;
    let dmax = 0;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs((bx - ax) * (ay - pts[i][1]) - (ax - pts[i][0]) * (by - ay)) / len;
      if (d > dmax) [dmax, best] = [d, i];
    }
    if (dmax > tol && best > 0) {
      keep[best] = 1;
      stack.push([a, best], [best, b]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

const area = (r) => Math.abs(r.reduce((s, [x, y], i) => s + x * r[(i + 1) % r.length][1] - r[(i + 1) % r.length][0] * y, 0) / 2);
const CONTINENT = {
  Africa: 'af',
  Asia: 'as',
  Europe: 'eu',
  'North America': 'na',
  'South America': 'sa',
  Oceania: 'oc',
  'Seven seas (open ocean)': 'oc',
};

const out = [];
for (const f of geo.features) {
  const p = f.properties;
  if (p.CONTINENT === 'Antarctica') continue;
  const iso3 = [p.ISO_A3, p.ISO_A3_EH, p.ADM0_A3].find((v) => v && v !== '-99');
  const iso2 = [p.ISO_A2, p.ISO_A2_EH].find((v) => v && v !== '-99') ?? '';
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  let rings = polys.map((poly) => poly[0]); // outer rings only: holes are invisible at this scale
  const biggest = Math.max(...rings.map(area));
  rings = rings
    .filter((r) => area(r) >= MIN_AREA || area(r) === biggest)
    .map((r) => simplify(r.slice(0, -1), TOLERANCE))
    .filter((r) => r.length >= 3);
  const d = rings
    .map((r) => r.map(([x, y]) => `${Math.round(x * 10)} ${Math.round(y * 10)}`).join(' '))
    .join('|');
  out.push({ id: iso3, a2: iso2, c: CONTINENT[p.CONTINENT] ?? 'oc', n: p.NAME, d });
}
out.sort((a, b) => a.id.localeCompare(b.id));

const file = path.join(root, 'packages/runtime/src/data/world.ts');
const code = `// Generated by scripts/gen-world-map.mjs from Natural Earth 1:110m Admin 0 – Countries (public domain).
// Do not edit. Each ring is "lon lat lon lat …" in tenths of a degree; rings are separated by "|".
export interface WorldCountry {
  /** ISO 3166-1 alpha-3 code. */
  id: string;
  /** ISO 3166-1 alpha-2 code ('' when Natural Earth has none). */
  a2: string;
  /** Continent: af, as, eu, na, sa, oc. */
  c: string;
  n: string;
  d: string;
}

export const WORLD: WorldCountry[] = ${JSON.stringify(out)};
`;
const options = (await prettier.resolveConfig(file)) ?? {};
writeFileSync(file, await prettier.format(code, { ...options, filepath: file }));
const pts = out.reduce((s, c) => s + c.d.split(/[ |]/).length / 2, 0);
console.log(`wrote ${path.relative(root, file)}: ${out.length} countries, ${Math.round(pts)} points`);
