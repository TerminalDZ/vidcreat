// Generates docs/components.md from the component schemas (single source of truth).
// Usage: node scripts/gen-components-doc.mjs   (requires `pnpm build`)
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import prettier from 'prettier';
import { COMPONENTS, ICONS_LIST, episodeJsonSchema } from '../packages/core/dist/index.js';

const target = fileURLToPath(new URL('../docs/components.md', import.meta.url));

/** The formatted Markdown of docs/components.md. */
export async function componentsDoc() {
  const schema = episodeJsonSchema()['x-components'];
  const typeOf = (s) => {
    if (!s) return 'any';
    if (s.enum && s.enum.length > 40) return 'icon name ([list](#icons))';
    if (s.enum) return s.enum.map((v) => `\`${v}\``).join(' \\| ');
    if (s.anyOf) return [...new Set(s.anyOf.map(typeOf))].join(' \\| ');
    if (s.type === 'array') return s.items?.anyOf ? `(${typeOf(s.items)})[]` : `${typeOf(s.items)}[]`;
    if (s.type === 'object' && s.properties) return `{ ${Object.keys(s.properties).join(', ')} }`;
    return Array.isArray(s.type) ? s.type.join(' \\| ') : (s.type ?? 'any');
  };
  const TIME = new Set(['at', 'until']);
  let md = `# Component reference

Generated from the schemas in \`packages/core/src/components/schemas.ts\` by
\`node scripts/gen-components-doc.mjs\`. Props are strict: unknown keys are errors with a
"did you mean" hint.

Conventions:
- Keys named \`at\` and \`until\` (at any depth), and \`strike\`/\`highlight\` when not booleans, are
  **time expressions**: \`12.5s\`, \`l7\`, \`l7+0.4\`, \`l7.end\`, \`l7:'word'\`, \`l7:'word'#2\`, \`l7.3\`, \`@scene.end\`.
- Keys named \`color\`, \`accent\`, \`danger\` and \`colors[]\` take a **theme color name**
  (\`lime\`, \`cyan\`, \`red\`, \`amber\`, \`violet\`, \`ink\`, \`dim\`, …) or a CSS color.
- \`from\`/\`to\` endpoints are an element id (\`api\`), an element side (\`api.left|right|top|bottom|center\`)
  or a point \`{x, y}\` in stage coordinates.
- Every element also takes the common keys: \`id, place, size, col, layer, z, enter, exit, states, fx, sfx\`
  (see [authoring.md](authoring.md)).

| Component | Default size | Default enter | Layer | Purpose |
|---|---|---|---|---|
${Object.values(COMPONENTS)
  .map(
    (c) =>
      `| [\`${c.name}\`](#${c.name}) | ${c.size.w}×${c.size.h} | ${c.enter ?? 'pop'} | ${c.layer ?? 'base'} | ${c.description} |`,
  )
  .join('\n')}
`;
  for (const c of Object.values(COMPONENTS)) {
    const s = schema[c.name];
    const props = s.properties ?? s.allOf?.[0]?.properties ?? {};
    const req = new Set(s.required ?? []);
    md += `\n## ${c.name}\n\n${c.description}\n\n| Prop | Type | Default | Required |\n|---|---|---|---|\n`;
    for (const [k, v] of Object.entries(props)) {
      const def = v.default !== undefined ? `\`${JSON.stringify(v.default)}\`` : '';
      md += `| \`${k}\` | ${TIME.has(k) ? 'time' : typeOf(v)} | ${def} | ${req.has(k) && v.default === undefined ? 'yes' : ''} |\n`;
    }
  }
  md += `\n## Icons\n\n${ICONS_LIST.length} bundled icons: the ReelForge set and a subset of [Lucide](https://lucide.dev) (ISC, regenerated by \`node scripts/vendor-icons.mjs\`).\n\n${ICONS_LIST.map((n) => `\`${n}\``).join(', ')}\n`;
  const options = (await prettier.resolveConfig(target)) ?? {};
  return prettier.format(md, { ...options, filepath: target });
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(target, await componentsDoc());
  console.log('wrote docs/components.md');
}
