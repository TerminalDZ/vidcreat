# Generates speech fixtures with exact ground-truth timings for the cue aligners (Windows only: SAPI).
# Each fixture folder gets voice.wav (16 kHz mono PCM), episode.yaml (the script) and truth.json
# ({ lines: { l1: seconds }, words: { l1: [seconds…] } }) taken from SAPI word-boundary events.
#
#   powershell -ExecutionPolicy Bypass -File scripts/make-speech-fixture.ps1
param([string]$Out = (Join-Path $PSScriptRoot '..\fixtures\align'))
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Speech
Add-Type -ReferencedAssemblies System.Speech -TypeDefinition @'
using System;
using System.Collections.Generic;
using System.Speech.Synthesis;
using System.Speech.AudioFormat;
public static class RfSpeech {
  public class Word { public int Char; public double T; public string Text; }
  public static List<Word> Speak(string ssml, string wav) {
    var words = new List<Word>();
    using (var s = new SpeechSynthesizer()) {
      s.SpeakProgress += (o, e) => words.Add(new Word { Char = e.CharacterPosition, T = e.AudioPosition.TotalSeconds, Text = e.Text });
      s.SetOutputToWaveFile(wav, new SpeechAudioFormatInfo(16000, AudioBitsPerSample.Sixteen, AudioChannel.Mono));
      s.SpeakSsml(ssml);
      s.SetOutputToNull();
    }
    return words;
  }
}
'@

function Escape([string]$t) { [Security.SecurityElement]::Escape($t) }
function WriteUtf8([string]$file, [string]$text) {
  [IO.File]::WriteAllText($file, $text.Replace("`r`n", "`n"), (New-Object Text.UTF8Encoding $false))
}

function Make([string]$name, [string]$voice, [string]$rate, [double]$lead, [int[]]$gaps, [string[]]$lines) {
  $dir = Join-Path $Out $name
  New-Item -ItemType Directory -Force $dir | Out-Null
  $head = "<speak version=`"1.0`" xmlns=`"http://www.w3.org/2001/10/synthesis`" xml:lang=`"en-US`"><voice name=`"$voice`"><prosody rate=`"$rate`"><break time=`"$([int]($lead*1000))ms`"/>"
  $ssml = $head
  $spans = @()
  for ($i = 0; $i -lt $lines.Count; $i++) {
    $txt = Escape $lines[$i]
    $spans += , @($ssml.Length, ($ssml.Length + $txt.Length))
    $ssml += $txt
    if ($i -lt $lines.Count - 1) { $ssml += "<break time=`"$($gaps[$i % $gaps.Count])ms`"/>" }
  }
  $ssml += '<break time="700ms"/></prosody></voice></speak>'
  $words = [RfSpeech]::Speak($ssml, (Join-Path $dir 'voice.wav'))
  $truthLines = [ordered]@{}
  $truthWords = [ordered]@{}
  for ($i = 0; $i -lt $lines.Count; $i++) {
    $id = "l$($i + 1)"
    $w = @($words | Where-Object { $_.Char -ge $spans[$i][0] -and $_.Char -lt $spans[$i][1] })
    $truthLines[$id] = [math]::Round($w[0].T, 3)
    $count = ($lines[$i] -split '\s+' | Where-Object { $_ }).Count
    if ($w.Count -eq $count) { $truthWords[$id] = @($w | ForEach-Object { [math]::Round($_.T, 3) }) }
  }
  $json = [ordered]@{ voice = $voice; rate = $rate; lines = $truthLines; words = $truthWords } | ConvertTo-Json -Depth 5 -Compress
  WriteUtf8 (Join-Path $dir 'truth.json') ($json + "`n")
  $yaml = @("# Alignment fixture generated by scripts/make-speech-fixture.ps1 (SAPI $voice). Do not edit by hand.",
    'meta:', "  id: $name", '  title: Alignment fixture', '  preset: tiktok', '  lang: en-US', '', 'script:')
  foreach ($l in $lines) { $yaml += "  - text: '$($l.Replace("'", "''"))'" }
  $yaml += @('', 'scenes:', '  - id: main', '    at: l1')
  WriteUtf8 (Join-Path $dir 'episode.yaml') (($yaml -join "`n") + "`n")
  "{0}: {1} lines, {2} with word truth" -f $name, $lines.Count, $truthWords.Count
}

